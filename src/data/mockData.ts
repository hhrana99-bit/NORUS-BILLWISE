const createFieldMeta = (
  defaultStatus: FieldVerificationStatus,
  overrides: Partial<Record<InvoiceFieldKey, Partial<InvoiceFieldMeta>>> = {}
): Record<InvoiceFieldKey, InvoiceFieldMeta> => {
  const base: Record<InvoiceFieldKey, InvoiceFieldMeta> = {
    supplierName: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Header Block, Page 1)',
    },
    supplierGstin: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Tax Registration Block, Page 1)',
    },
    invoiceNumber: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Document Metadata, Page 1)',
    },
    invoiceDate: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Document Metadata, Page 1)',
    },
    taxableAmount: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Summary Totals, Page 1)',
    },
    cgst: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (GST Breakup Table, Page 1)',
    },
    sgst: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (GST Breakup Table, Page 1)',
    },
    igst: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (GST Breakup Table, Page 1)',
    },
    totalAmount: {
      status: defaultStatus,
      evidenceNote: 'Source Evidence: Pending OCR region mapping (Grand Total Box, Page 1)',
    },
  };

  (Object.keys(overrides) as InvoiceFieldKey[]).forEach((key) => {
    const patch = overrides[key];
    if (patch) {
      base[key] = { ...base[key], ...patch };
    }
  });

  return base;
};

